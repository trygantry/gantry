import fs from 'fs';
import path from 'path';
import process from 'process';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/modules/generated/gantry-contracts.d.ts');
const contracts = [
  ['MobileAuditReport', 'mobile-audit-report.schema.json'],
  ['MobileRelease', 'mobile-release.schema.json'],
  ['ReleaseCandidate', 'release-candidate.schema.json'],
  ['ReleaseAudit', 'release-audit.schema.json'],
  ['ReleaseEvent', 'release-event.schema.json'],
  ['ReleaseEvidenceLink', 'release-evidence-link.schema.json'],
  ['FindingResolution', 'finding-resolution.schema.json'],
  ['HumanReleaseDecision', 'human-release-decision.schema.json'],
  ['ReleaseFindingWaiver', 'release-finding-waiver.schema.json'],
  ['ReleasePacket', 'release-packet.schema.json'],
  ['ReleaseCandidateDiff', 'release-candidate-diff.schema.json'],
  ['ReleasePortfolio', 'release-portfolio.schema.json']
];

const literal = (value) => JSON.stringify(value);

function schemaType(schema, defs = {}, seen = new Set()) {
  if (!schema || typeof schema !== 'object') return 'unknown';
  if ('const' in schema) return literal(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map(literal).join(' | ') || 'never';
  if (Array.isArray(schema.oneOf)) return schema.oneOf.map(item => schemaType(item, defs, seen)).join(' | ');
  if (Array.isArray(schema.anyOf)) return schema.anyOf.map(item => schemaType(item, defs, seen)).join(' | ');
  if (schema.$ref?.startsWith('#/$defs/')) {
    const name = schema.$ref.slice('#/$defs/'.length);
    if (seen.has(name)) return 'unknown';
    return schemaType(defs[name], defs, new Set([...seen, name]));
  }
  if (Array.isArray(schema.type)) {
    return schema.type.map(type => schemaType({ ...schema, type }, defs, seen)).join(' | ');
  }
  if (schema.type === 'array') return `Array<${schemaType(schema.items, defs, seen)}>`;
  if (schema.type === 'object' || schema.properties || schema.additionalProperties) {
    const required = new Set(schema.required || []);
    const fields = Object.entries(schema.properties || {}).map(([name, property]) => {
      const optional = required.has(name) ? '' : '?';
      return `${JSON.stringify(name)}${optional}: ${schemaType(property, defs, seen)};`;
    });
    if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
      fields.push(`[key: string]: ${schemaType(schema.additionalProperties, defs, seen)};`);
    } else if (schema.additionalProperties !== false && fields.length === 0) {
      fields.push('[key: string]: unknown;');
    }
    return `{ ${fields.join(' ')} }`;
  }
  if (schema.type === 'string') return 'string';
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (schema.type === 'boolean') return 'boolean';
  if (schema.type === 'null') return 'null';
  return 'unknown';
}

const lines = [
  '// Generated by scripts/generate-frontend-contracts.mjs. Do not edit by hand.',
  '// Source of truth: schemas/*.schema.json',
  ''
];
for (const [name, file] of contracts) {
  const schema = JSON.parse(fs.readFileSync(path.join(root, 'schemas', file), 'utf8'));
  lines.push(`export type ${name} = ${schemaType(schema, schema.$defs || {})};`);
  lines.push('');
}
const output = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    console.error('Generated frontend contracts are stale. Run npm run generate:contracts.');
    process.exit(1);
  }
  console.log('Generated frontend contracts match the published schemas.');
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, output);
  console.log(`Wrote ${path.relative(root, outputPath)}`);
}
